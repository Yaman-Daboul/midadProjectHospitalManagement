"use client"; // 👈 تحويل الـ layout إلى مكون عميل لتشغيل الـ Providers معاً

import { useState } from "react";
import "./global.css";
import { AuthProvider } from "@/contexts/AuthContext";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query"; // 👈 استيراد حزم المخططات وجلب البيانات

export default function RootLayout({ children }: { children: React.ReactNode }) {
  // 🌐 إنشاء نسخة الـ QueryClient لتعمل داخل المتصفح
  const [queryClient] = useState(() => new QueryClient());

  return (
    <html lang="ar" dir="rtl">
      <body>
        <AuthProvider>
          <QueryClientProvider client={queryClient}>
            <div className="flex h-screen overflow-hidden bg-background">
              {children}
            </div>
          </QueryClientProvider>
        </AuthProvider>
      </body>
    </html>
  );
}






